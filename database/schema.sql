CREATE DATABASE IF NOT EXISTS taller_motos CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE taller_motos;

CREATE TABLE IF NOT EXISTS clients (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  email VARCHAR(150) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS bikes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  plate VARCHAR(10) NOT NULL UNIQUE,
  brand VARCHAR(60) NOT NULL,
  model VARCHAR(60) NOT NULL,
  cylinder INT UNSIGNED NULL,
  client_id INT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_bikes_client FOREIGN KEY (client_id) REFERENCES clients(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS work_orders (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  bike_id INT UNSIGNED NOT NULL,
  entry_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fault_description TEXT NOT NULL,
  status ENUM('RECIBIDA','DIAGNOSTICO','EN_PROCESO','LISTA','ENTREGADA','CANCELADA') NOT NULL DEFAULT 'RECIBIDA',
  total DECIMAL(12,2) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_wo_status (status),
  CONSTRAINT fk_wo_bike FOREIGN KEY (bike_id) REFERENCES bikes(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS work_order_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  work_order_id INT UNSIGNED NOT NULL,
  type ENUM('MANO_OBRA','REPUESTO') NOT NULL,
  description VARCHAR(255) NOT NULL,
  count INT UNSIGNED NOT NULL,
  unit_value DECIMAL(12,2) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT chk_item_count CHECK (count > 0),
  CONSTRAINT chk_item_value CHECK (unit_value >= 0),
  CONSTRAINT fk_item_wo FOREIGN KEY (work_order_id) REFERENCES work_orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;
